def load_data():
    """Returns texts, labels, groups.

    The same 24 situations are written in every variety, so sentence i of each
    variety shares a group id. Splits must keep a group together, otherwise the
    model sees the same topic under other labels during training.
    """
    texts, labels, groups = [], [], []
    for label, sentences in DATA.items():
        for i, s in enumerate(sentences):
            texts.append(s)
            labels.append(label)
            groups.append(i)
    return texts, labels, groups


